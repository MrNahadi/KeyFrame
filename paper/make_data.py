def confusion() -> str:
    preds = pd.read_parquet(paths.PROCESSED / "experiments" / "modelling_xgboost.parquet")
    counts = pd.crosstab(preds["y_true"], preds["y_pred"]).reindex(
        index=CLASSES, columns=CLASSES, fill_value=0
    )
    share = counts.div(counts.sum(axis=1), axis=0)
    lines = []
    for true in CLASSES:
        cells = []
        for pred in CLASSES:
            p = float(share.loc[true, pred])
            # Tint capped at 60% so the dark figures stay readable on every cell.
            shade = int(round(p * 60))
            colour = f"\\cellcolor{{accent!{shade}}}" if shade else ""
            cells.append(f"{colour}{p:.2f}")
        lines.append(f"{FAULT_NAME[true]} & " + " & ".join(cells) + r" \\")
    return "\n".join(lines) + "\n"


def replay_trace(m: Macros) -> str:
    replay = json.loads((paths.MODELS / "replays" / "AC_Fouling_75_Load.json").read_text())
    t0 = replay["frames"][0]["t"]
    switch_on = replay["switch_on_t"]
    alarm_t = next(fr["t"] for fr in replay["frames"] if fr["alarm"] != "Normal")
    m["ReplaySwitchMin"] = f"{(switch_on - t0) / 60:.1f}"
    m["ReplayAlarmMin"] = f"{(alarm_t - t0) / 60:.1f}"
    m["ReplayDelay"] = delay(alarm_t - switch_on)
    lines = ["t_min,temp_c,p_ac,p_normal"]
    for fr in replay["frames"]:
        temp = fr["sensors"]["charge_air_temp_after_cooler"]["value"]
        lines.append(
            f"{(fr['t'] - t0) / 60:.3f},{temp:.3f},{fr['probabilities']['AC']:.4f},{fr['probabilities']['Normal']:.4f}"
        )
    return "\n".join(lines) + "\n"


def switch_on_trace() -> str:
    clean = pd.read_parquet(
        paths.PROCESSED / "clean.parquet",
        columns=["run", "t", "label", "Charge Air IC Air Temp. Out"],
    )
    columns = {}
    for load in LOADS:
        run = clean[clean["run"] == f"AC_Fouling_{load}_Load"].sort_values("t")
        switch_on = run.loc[run["label"] != "Normal", "t"].min()
        minutes = (run["t"] - switch_on) / 60
        window = run[(minutes >= -30) & (minutes <= 60)]
        # One point per 30 s keeps the plot light without changing its shape.
        binned = window.groupby(((window["t"] - switch_on) // 30) * 0.5)[
            "Charge Air IC Air Temp. Out"
        ].mean()
        columns[f"l{load}"] = binned
    frame = pd.DataFrame(columns).sort_index()
    frame.index.name = "t_min"
    return frame.to_csv(float_format="%.3f", na_rep="nan")


def test_counts() -> str:
    """Counts of the automated tests, collected (not run) at generation time."""
    out = subprocess.run(
        ["uv", "run", "pytest", "--collect-only", "-q", "-p", "no:warnings"],
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    # The project's addopts make -q print one "file: count" line per test file.
    per_file = [int(n) for n in re.findall(r"^tests/\S+: (\d+)$", out, flags=re.M)]
    total = re.search(r"(\d+) tests? collected", out)
    python = sum(per_file) if per_file else int(total.group(1)) if total else 0
    if python == 0:
        raise RuntimeError(f"could not count the Python tests from:\n{out[-500:]}")
    web = subprocess.run(
        ["npx", "vitest", "list", "--json"],
        cwd=paths.ROOT / "web",
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    web_count = len(json.loads(web))
    m = Macros()
    m["TestsPython"] = str(python)
    m["TestsWeb"] = str(web_count)
    return m.text()


def build(out: Path, counts: bool = True) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    m = Macros()
    data_section(m)
    exported_model(m)
    baselines(m)
    lockbox(m)
    crosscheck(m)
    latency(m)
    writers: dict[str, Callable[[], str]] = {
        "coverage.tex": coverage_table,
        "ablation.tex": lambda: ablation(m),
        "models.tex": lambda: models(m),
        "anomaly.tex": lambda: anomaly(m),
        "calibration.tex": lambda: calibration(m),
        "physics.tex": lambda: physics(m),
        "grouped_shap.tex": grouped_shap,
        "sensitivity.csv": lambda: sensitivity(m),
        "confusion.tex": confusion,
        "replay_ac75.csv": lambda: replay_trace(m),
        "switchon_ac.csv": switch_on_trace,
    }
    written = []
    for name, writer in writers.items():
        (out / name).write_text(writer())
        written.append(out / name)
    hyper = best_model(m)
    settings, per_run = alarms(m)
    for name, text in (
        ("hyperparameters.tex", hyper),
        ("alarm_settings.tex", settings),
        ("alarms.tex", per_run),
    ):
        (out / name).write_text(text)
        written.append(out / name)
    (out / "results.tex").write_text(m.text())
    written.append(out / "results.tex")
    if counts:
        (out / "counts.tex").write_text(test_counts())
        written.append(out / "counts.tex")
    return written


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=PAPER / "data")
    parser.add_argument("--no-counts", action="store_true", help="skip collecting test counts")
    args = parser.parse_args()
    for path in build(args.out, counts=not args.no_counts):
        print(path.relative_to(paths.ROOT) if path.is_relative_to(paths.ROOT) else path)


if __name__ == "__main__":
    main()
