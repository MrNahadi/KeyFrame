def lockbox(m: Macros) -> None:
    table = results("07_lockbox")
    allrow = table[table["scope"] == "all"].iloc[0]
    m["LockShare"] = f"{100 * allrow['share']:.0f}"
    m["LockLabel"] = FAULT_NAME[allrow["label"]].lower()


def physics(m: Macros) -> str:
    text = (paths.REPORTS / "physics_check.md").read_text()
    result = re.search(r"Result: (\d) of 5 faults pass", text)
    assert result, "physics check result line not found"
    m["PhysPassed"] = result.group(1)
    lines = []
    for fault in FAULTS:
        row = re.search(rf"^\| {fault} \|(.+)$", text, flags=re.M)
        assert row, f"physics check row for {fault} not found"
        cells = [c.strip() for c in row.group(1).split("|")]
        match, day, passed = cells[2], cells[3], cells[4]
        day_word = "yes" if "Yes" in day else "no"
        pass_word = "\\textbf{pass}" if "Yes" in passed else "fail"
        lines.append(f"{FAULT_NAME[fault]} & {match} & {day_word} & {pass_word}" + r" \\")
    return "\n".join(lines) + "\n"


def grouped_shap() -> str:
    table = results("06_grouped_shap").set_index("Unnamed: 0")
    lines = []
    for group in GROUPS:
        cells = []
        for cls in FAULTS:
            value = float(table.loc[group, cls])
            text = "0.00" if round(value, 2) == 0 else f"{value:+.2f}".replace("-", "$-$")
            top = table.loc[GROUPS, cls].astype(float).idxmax() == group
            cells.append(f"\\textbf{{{text}}}" if top else text)
        lines.append(f"{group.capitalize()} & " + " & ".join(cells) + r" \\")
    return "\n".join(lines) + "\n"


def crosscheck(m: Macros) -> None:
    table = results("06_crosscheck")
